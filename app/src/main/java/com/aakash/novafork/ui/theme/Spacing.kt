package com.aakash.novafork.ui.theme

import androidx.compose.ui.unit.dp

/**
 * The spacing scale: every gap in the shared components is one of these. Page gutter on the phone
 * is [lg], the gap between sections [xl], and a card sits [sm] above its caption.
 */
object Spacing {
    val xs = 4.dp
    val sm = 8.dp
    val md = 12.dp
    val lg = 16.dp
    val xl = 24.dp
    val xxl = 32.dp
}
